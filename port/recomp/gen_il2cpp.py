_W = {}


def _worker_init(nso, starts, emitted, opts):
    _W.update(nso=nso, starts=starts, emitted=emitted, opts=opts, emitter=None)


def _emitter():
    e = _W['emitter']
    if e is None:
        mod = Module('main', _W['nso'], BASE, 'c')
        e = _W['emitter'] = Il2cppEmitter(mod, set(_W['starts'].tolist()), ehtab.read(mod), **_W['opts'])
        _W['emitted_set'] = set(_W['emitted'].tolist())
    return e


def _emit_chunk(task):
    number, path, fns = task
    t0 = time.perf_counter()
    e = _emitter()
    e.stats.clear()
    e.unsupported.clear()
    e.examples = {}
    text, refs = chunk_text(number, e, fns)
    error = None
    try:
        written = up.write_if_changed(Path(path), text)
    except OSError as ex:
        written, error = False, f'{path}: {ex}'
    return {'number': number, 'file': Path(path).name, 'functions': len(fns), 'bytes': len(text),
            'written': written, 'error': error, 'seconds': time.perf_counter() - t0, 'stats': dict(e.stats),
            'unsupported': dict(e.unsupported), 'examples': e.examples,
            'boundary': sorted(refs - _W['emitted_set'])}


