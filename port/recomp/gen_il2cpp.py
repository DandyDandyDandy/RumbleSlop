def eh_notes():
    """Why the exception scheme is sound in the generated C (kept here so the reasoning lives beside the code).

    1. Every guest call (bl -> f_x(c), blr -> rt_dispatch(c)) is followed by a test of c->eh_unwinding before any
       other guest instruction runs. __cxa_throw, _Unwind_Resume and friends are reached through lifted PLT stubs
       (a musttail rt_dispatch), so they are ordinary calls that return with the flag set; the code after such a
       `noreturn` call is never run, because the test leaves first. Nothing in the generator assumes a call does not
       return: a call that ends a function is followed by the test and then by a tail call or a trap.
    2. Tail calls (b to another function, br through rt_dispatch) are `musttail return`: the callee returns to this
       function's caller, whose call site tests the flag.
    3. A call site with a pad: registers. The real unwinder enters a pad with X19-X29, SP and D8-D15 as they were in
       this frame when the call was made (callees restore them on the way out). Lifted frames that are abandoned by
       an early return do not run their epilogues, so the function snapshots exactly that state before the call
       (eh_save) and restores it before the pad (eh_restore). A function with any such site keeps no guest register
       in a C local (regs.plan with 0 locals), so the Cpu is the only copy: eh_save reads current values and the pad
       sees what eh_restore and rt_eh_enter (x0, x1) wrote.
    4. Flags. NZCV lives in a C local `Flags F`. A pad is compiler-generated code that starts with fresh
       computations; AAPCS64 code does not read flags across a call and the unwinder does not define them at a pad.
       The call -> pad edge is added to the function's flow, so flags.plan sees the pad reached with the `CALL`
       pseudo-definition (no definition), exactly like the instruction after a call.
    5. A function whose computed `br` could not be resolved re-enters through fb_<entry> with every instruction
       labelled; it keeps registers and flags in the Cpu, has the EhSave local in fb_<entry>, and pads are labels
       there as everywhere.
    6. Functions without pads keep upstream's register locals and callee-saved trust: when a callee returns
       unwinding they return at once without touching the Cpu; when a callee caught an exception it restored its
       own snapshot and then ran its normal epilogue, so X19-X29 and SP are what AAPCS64 promises.
    """


