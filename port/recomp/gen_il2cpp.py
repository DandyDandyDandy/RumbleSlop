def read_tsv(path):
    with open(path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f, delimiter='\t'))


def lift_ranges(closure):
    """Sorted (start, end) arrays of the lift set, absolute."""
    s, e = [], []
    # extra_lift.tsv (port/recomp/extra_lift.py): the CRIWARE native library and the Nintendo plug-in glue.
    for path in (closure / 'lift_functions.tsv.gz', closure / 'extra_lift.tsv'):
        if not path.exists():
            raise SystemExit(f'missing table {path}')
        with (gzip.open(path, 'rt', encoding='utf-8') if path.suffix == '.gz' else open(path, encoding='utf-8')) as f:
            next(f)
            for line in f:
                p = line.split('\t', 3)
                s.append(int(p[0], 16) + BASE)
                e.append(int(p[1], 16) + BASE)
    order = np.argsort(s)
    return np.asarray(s, dtype=np.int64)[order], np.asarray(e, dtype=np.int64)[order]


def plt_stubs(mod):
    """{stub address: (GOT slot, symbol)} for every PLT stub `adrp x16; ldr x17, [x16, #o]; add x16, x16, #o; br x17`."""
    w = mod.words
    n = len(w)
    i = np.flatnonzero((w[:n - 3] & 0x9F00001F) == 0x90000010)
    i = i[((w[i + 1] & 0xFFC003FF) == 0xF9400211) & ((w[i + 2] & 0xFFC003FF) == 0x91000210) & (w[i + 3] == 0xD61F0220)]
    syms = mod.nso.syms
    slot_sym = {mod.base + off: syms[sym][0] for off, typ, sym, _ in mod.nso.relocs if typ == 1026}
    out = {}
    for k in i.tolist():
        a = mod.lo + 4 * k
        v = int(w[k])
        imm = ((v >> 5) & 0x7FFFF) << 2 | ((v >> 29) & 3)
        if imm & (1 << 20):
            imm -= 1 << 21
        slot = (a & ~0xFFF) + (imm << 12) + ((int(w[k + 1]) >> 10) & 0xFFF) * 8
        if slot in slot_sym:
            out[a] = (slot, slot_sym[slot])
    return out


def direct_targets(mod, lo_idx, hi_idx):
    """Absolute targets of every B/BL/B.cond/CBZ/TBZ in the word ranges [lo_idx[i], hi_idx[i])."""
    w = mod.words
    mark = np.zeros(len(w) + 1, dtype=np.int32)
    np.add.at(mark, lo_idx, 1)
    np.add.at(mark, hi_idx, -1)
    inside = np.cumsum(mark[:-1]) > 0
    out = []
    for mask, val, nb, sh in ((0x7C000000, 0x14000000, 26, 0), (0xFE000010, 0x54000000, 19, 5),
                              (0x7E000000, 0x34000000, 19, 5), (0x7E000000, 0x36000000, 14, 5)):
        s = np.flatnonzero(((w & mask) == val) & inside).astype(np.int64)
        out.append(s + up._sext((w[s] >> sh) & ((1 << nb) - 1), nb))
    t = np.unique(np.concatenate(out))
    return mod.lo + 4 * t


ENGINE_NAMES = {'_ZdlPv': 'operator delete', '_Znwm': 'operator new', '_Znam': 'operator new[]',
                '_ZdaPv': 'operator delete[]'}


def boundary_info(closure, targets):
    """[(addr, kind, name)] for the boundary targets, from the closure tables."""
    direct = {int(r['target'], 16) + BASE: r for r in read_tsv(closure / 'boundary_direct.tsv')}
    engine = {int(r['target'], 16) + BASE: r for r in read_tsv(closure / 'boundary_runtime_to_engine.tsv')}
    out = []
    for a in sorted(targets):
        d, e = direct.get(a), engine.get(a)
        kind, name = 'unknown', ''
        if d:
            ident = d['identification']
            if ident.startswith('native for '):
                kind, name = 'pinvoke', ident
            else:
                kind, name = d['region'], ENGINE_NAMES.get(ident, ident)
        if e:
            kind = 'engine'
            name = ENGINE_NAMES.get(e['export_name'], e['export_name']) or name
            if not name and e['hint']:
                name = f'sub_{a - BASE:x} ({e["hint"]})'
        if not name:
            name = f'sub_{a - BASE:x}'
        out.append((a, kind, name))
    return out


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def estimate(mod, s_idx, e_idx):
    w = mod.words
    cost = np.full(len(w), up.EST_INT, dtype=np.int64)
    cost[(w & 0x0E000000) == 0x0E000000] = up.EST_SIMD
    cost[((w & 0x0A000000) == 0x08000000) & (((w >> 26) & 1) == 1)] = up.EST_SIMD_LDST
    cost[(w & 0xFC000000) == 0x94000000] += EST_CALL           # BL
    cost[(w & 0xFFFFFC1F) == 0xD63F0000] += EST_CALL           # BLR
    has_br = ((w & 0xFFFFFC1F) == 0xD61F0000).astype(np.int64)
    csum = np.concatenate([[0], np.cumsum(cost)])
    bsum = np.concatenate([[0], np.cumsum(has_br)])
    size = csum[e_idx] - csum[s_idx] + up.EST_FN
    with_br = (bsum[e_idx] - bsum[s_idx]) > 0
    size[with_br] += (e_idx[with_br] - s_idx[with_br]) * up.EST_BR_LABELS
    return size


def split_pads_removed(mod, S):
    """S without the starts that would cut a call off from its landing pad.

    discover() takes every address an ADRP + ADD pair seems to build for a function start; a pair that is not one
    (the register was set again in between) can name the middle of a function. Where the exception table says a
    call and its landing pad lie on both sides of such an address it cannot be a start: the function is one piece.
    """
    drop = np.zeros(len(S), dtype=bool)
    for f in ehtab.read(mod):
        for a, b, pad, _ in f.sites:
            if pad:
                lo, hi = min(a, pad), max(b - 1, pad)
                drop[np.searchsorted(S, lo, side='right'):np.searchsorted(S, hi, side='right')] = True
    if drop.any():
        print(f'main: {int(drop.sum())} discovered starts between a call and its landing pad are not starts: '
              f'{[hex(int(a)) for a in S[drop][:8]]}', file=sys.stderr, flush=True)
    return S[~drop]


