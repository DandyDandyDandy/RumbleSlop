class Il2cppEmitter(up.Emitter):
    def __init__(self, mod, starts, fdes, reg_locals=regs.LOCALS, callee_saved=True):
        super().__init__(mod, starts, None, reg_locals, callee_saved)
        self.fde_starts = [f.start for f in fdes]
        self.fdes = fdes
        self.examples = {}

    def eh_sites(self, entry, end):
        """[(start, end, pad, action)] with a pad, and the LSDA address, for the function containing entry."""
        i = bisect.bisect_right(self.fde_starts, entry) - 1
        if i < 0:
            return 0, []
        f = self.fdes[i]
        if not f.lsda or entry >= f.end:
            return 0, []
        return f.lsda, [s for s in f.sites if s[2]]

    def function(self, entry, end):
        """(lines of C, referenced function starts) for the guest function [entry, end)."""
        mod, starts = self.mod, self.starts
        insns = [mod.lift(a) for a in range(entry, end, 4)]
        labels, tables = self.scan(insns, entry, end)
        for i, ins in enumerate(insns):
            if ins.kind == 'trap' and ins.code.startswith('rt_udf') and '/*' in ins.code:
                msg = re.sub(r'\b[0-9a-f]{8}\b', '', ins.code[ins.code.index('/*') + 2:ins.code.rindex('*/')]).strip()
                ex = self.examples.setdefault(msg, [])
                if len(ex) < 3:
                    ex.append(entry + 4 * i)
        refs = set()

        # Exception call sites: {call instruction address: (pad, action)}
        lsda, sites = self.eh_sites(entry, end)
        covered = {}
        if sites:
            lo = [s[0] for s in sites]
            for i, ins in enumerate(insns):
                if ins.kind in ('bl', 'blr'):
                    ip = entry + 4 * i + 3   # return address - 1, as the personality routine looks it up
                    j = bisect.bisect_right(lo, ip) - 1
                    if j >= 0 and ip < sites[j][1]:
                        pad = sites[j][2]
                        if not entry <= pad < end:
                            raise ValueError(f'{entry:#x}: landing pad {pad:#x} of the call at {entry + 4 * i:#x} '
                                             f'is outside the function piece [{entry:#x}, {end:#x})')
                        covered[entry + 4 * i] = (pad, sites[j][3])
        has_pads = bool(covered)
        labels |= {p for p, _ in covered.values()}

        all_labels = 'all' in tables.values()
        if all_labels:
            labels = set(range(entry, end, 4))
        local = not all_labels
        spill, reload, reload_call = (regs.SPILL, regs.RELOAD, regs.RELOAD_CALL) if local else ('', '', '')
        succ = None
        if local:
            succ = self.flow(insns, entry, end, tables)
            for a, (pad, _) in covered.items():
                succ[(a - entry) // 4].append((pad - entry) // 4)
        fp = self.flag_plan(insns, entry, end, tables, succ) if local else None
        if fp and fp.used:
            self.stats['local_flag_functions'] += 1
            self.stats['flag_reads_after_call'] += fp.after_call
            self.stats['flag_entry_functions'] += fp.entry

        def fx(i, code):
            return fp.rewrite(i, code) if fp and fp.used else code

        def publish(i):
            return fp.publish(i) if fp and fp.used else ''

        def jump(t, i):
            if entry <= t < end:
                return f'goto L_{t:x};'
            if t in starts:
                refs.add(t)
                return f'{publish(i)}{spill}{MUSTTAIL} {fname(t)}(c);'
            self.stats['external_branches'] += 1
            return f'{publish(i)}{spill}c->pc = {hx(t)}; {MUSTTAIL} rt_dispatch(c);'

        ehs = '    EhSave ehs;' if has_pads else None
        if all_labels:
            fb = f'fb_{entry:x}'
            cases = ' '.join(f'case {hx(t)}: goto L_{t:x};' for t in range(entry, end, 4))
            redispatch = f'{MUSTTAIL} {fb}(c);'
            out = [f'static void {fb}(Cpu *c);',
                   f'void {fname(entry)}(Cpu *c) {{', f'    FN_ENTER({hx(entry)});{hook_line(entry)}', f'    c->pc = {hx(entry)};',
                   f'    {redispatch}', '}',
                   f'static void {fb}(Cpu *c) {{']
            if ehs:
                out.append(ehs)
            out += [f'    switch (c->pc) {{ {cases} default: break; }}', f'    {MUSTTAIL} rt_dispatch(c);']
        else:
            redispatch = f'{MUSTTAIL} rt_dispatch(c);'
            out = [f'void {fname(entry)}(Cpu *c) {{', f'    FN_ENTER({hx(entry)});{hook_line(entry)}']
            if ehs:
                out.append(ehs)
            if fp.used:
                out.append('    ' + fp.decl())

        def eh(a):
            """(text before the call, text after it) for the call instruction at a."""
            self.stats['eh_checks'] += 1
            site = covered.get(a)
            if site is None:
                return '', ' EH_RET();'
            self.stats['eh_pad_sites'] += 1
            return 'eh_save(c, &ehs); ', f' EH_PAD({hx(lsda)}, {site[1]}, L_{site[0]:x});'

        def call(t, a):
            pre, post = eh(a)
            if t in starts:
                refs.add(t)
                return f'{pre}c->x[30] = {hx(a + 4)}; {spill}{fname(t)}(c);{post}{reload_call}'
            self.stats['external_calls'] += 1
            return f'{pre}c->x[30] = {hx(a + 4)}; {spill}c->pc = {hx(t)}; rt_dispatch(c);{post}{reload_call}'

        def op(i, code):
            code = fx(i, code)
            return f'{spill}{code}{reload}' if regs.ESCAPE.search(code) else code

        body = []   # (instruction index or None for a label, line)

        def emit(i, line):
            body.append((i, line))

        k = None
        for i, ins in enumerate(insns):
            a = entry + 4 * i
            if a in labels:
                emit(None, f'L_{a:x}:;')
            k = ins.kind
            if k == 'op':
                emit(i, '    ' + op(i, ins.code))
            elif k == 'trap':
                emit(i, f'    {spill}{fx(i, ins.code)}')
            elif k in ('b', 'bcond'):
                j = jump(ins.target, i)
                emit(i, '    ' + j if k == 'b' else f'    if ({fx(i, ins.cond)}) {{ {j} }}')
            elif k == 'bl':
                emit(i, '    ' + call(ins.target, a))
            elif k == 'blr':
                pre, post = eh(a)
                emit(i, f'    {pre}c->pc = {ins.target}; c->x[30] = {hx(a + 4)}; {spill}rt_dispatch(c);{post}'
                        f'{reload_call}')
            elif k == 'br':
                jt = tables.get(a)
                if jt == 'all':
                    emit(i, f'    c->pc = {ins.target}; {redispatch}')
                elif jt:
                    cases = ' '.join(f'case {hx(t)}: goto L_{t:x};' for t in jt)
                    emit(i, f'    switch ({ins.target}) {{ {cases} default: break; }}')
                    emit(i, f'    {publish(i)}{spill}c->pc = {ins.target}; {redispatch}')
                else:
                    emit(i, f'    {publish(i)}{spill}c->pc = {ins.target}; {MUSTTAIL} rt_dispatch(c);')
            elif k == 'ret':
                emit(i, f'    {spill}return;')
            else:
                raise ValueError(f'{a:#x}: unknown instruction kind {k!r}')
        n = len(insns)
        if k not in TERMINATORS:   # runs off its end: into the next function, or into padding / data
            if end in starts:
                self.stats['fallthrough_tail'] += 1
                emit(n, '    ' + jump(end, n))
            else:
                self.stats['fallthrough_trap'] += 1
                emit(n, f'    {spill}rt_udf(c, {hx(end)});')
        if local:
            texts = [''] * (n + 1)
            for i, line in body:
                if i is not None:
                    texts[i] += line
            clean = {i for i, ins in enumerate(insns)
                     if ins.kind in ('bl', 'blr') or (ins.kind == 'op' and regs.RELOAD in texts[i])}
            # A function with landing pads keeps every register in the Cpu (eh_notes() 3).
            rp = regs.plan(texts, succ, clean, 0 if has_pads else self.reg_locals,
                           frozenset() if has_pads else self.kept)
            if rp.regs:
                out.append('    ' + rp.decl())
            self.stats['local_reg_functions'] += bool(rp.regs)
            out += [line if i is None else rp.resolve(i, line) for i, line in body]
        else:
            out += [line for _, line in body]
        out.append('}')
        self.stats['functions'] += 1
        self.stats['instructions'] += len(insns)
        self.stats['eh_pad_functions'] += has_pads
        self.stats['eh_pads'] += len({p for p, _ in covered.values()})
        self.stats['lsda_functions'] += bool(lsda)
        return out, refs


def chunk_text(number, emitter, fns):
    body, refs = [], set()
    for entry, end in fns:
        try:
            lines, r = emitter.function(entry, end)
        except Exception as e:
            raise RuntimeError(f'function {entry:#x}-{end:#x}: {type(e).__name__}: {e}') from e
        body.append('\n'.join(lines))
        refs |= r
    protos = ''.join(f'void {fname(r)}(Cpu *c);\n' for r in sorted(refs))
    return header(f'main chunk {number:04d}') + CHUNK_PRELUDE + '\n' + protos + '\n' + '\n\n'.join(body) + '\n', refs


